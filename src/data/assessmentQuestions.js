/**
 * Get questions by assessment type
 */
export function getQuestionsByType(assessmentType) {
  return ASSESSMENT_QUESTIONS.filter(q => q.assessmentType === assessmentType);
}

/**
 * Get all questions
 */
export function getAllQuestions() {
  return ASSESSMENT_QUESTIONS;
}

/**
 * Get question by ID
 */
export function getQuestionById(questionId) {
  return ASSESSMENT_QUESTIONS.find(q => q.questionId === questionId);
}
